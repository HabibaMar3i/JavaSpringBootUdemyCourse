public class Inheritance {
    public static void main(String[] args) {
        VeryAdvCalc calc = new VeryAdvCalc();
        System.out.println(calc.add(4, 5));
        System.out.println(calc.sub(9, 1));
        System.out.println(calc.multi(3, 2));
        System.out.println(calc.div(12, 3));
        System.out.println(calc.power(12, 3));
    }
}
