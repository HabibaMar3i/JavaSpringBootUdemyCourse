class Loops{
    public static void main(String a[]){
        // while loop
        int i = 1;
        while(i<=5){
            System.out.println(i);
            i++;
        }

        // do while loop
        int j = 1;
        do{
            System.out.println(j);
            j++;
        }while(j<=5);
    }
}